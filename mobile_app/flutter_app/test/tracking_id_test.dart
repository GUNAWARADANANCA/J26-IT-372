import 'package:flutter_test/flutter_test.dart';
import 'package:postassist_mobile/core/tracking_id.dart';

void main() {
  group('normalizeTrackingId', () {
    test('uppercases, strips spaces and maps look-alikes after the last dash', () {
      expect(normalizeTrackingId(' pa-demo-7k3m9q2xrh4 '), 'PA-DEMO-7K3M9Q2XRH4');
      expect(normalizeTrackingId('PA-DEMO-OIL'), 'PA-DEMO-011');
      expect(normalizeTrackingId('NODASH'), 'NODASH');
    });
  });

  group('isValidTrackingId', () {
    // Check characters computed with backend/app/services/tracking_id.py.
    test('accepts IDs whose check character matches', () {
      expect(isValidTrackingId('PA-DEMO-0000000000' '0'), isTrue);
      expect(isValidTrackingId('PA-DEMO-0000000001' '1'), isTrue);
    });

    test('accepts IDs generated by the backend', () {
      for (final id in [
        'PA-DEMO-45EY5FEKRXX',
        'PA-DEMO-9VZPX7VFG5J',
        'PA-DEMO-H7834YVJ8KN',
        'PA-DEMO-F6AYB260YTC',
        'PA-DEMO-ZQ42G0ZVPRF',
      ]) {
        expect(isValidTrackingId(id), isTrue, reason: id);
      }
    });

    test('rejects a single substituted character', () {
      expect(isValidTrackingId('PA-DEMO-0000000001' '2'), isFalse);
      expect(isValidTrackingId('PA-DEMO-1000000001' '1'), isFalse);
    });

    test('rejects wrong length and missing prefix', () {
      expect(isValidTrackingId('PA-DEMO-123'), isFalse);
      expect(isValidTrackingId('00000000000'), isFalse);
    });
  });

  group('parseScannedCode', () {
    test('reads a plain label value', () {
      final c = parseScannedCode('pa-demo-00000000000');
      expect(c.trackingId, 'PA-DEMO-00000000000');
      expect(c.token, isNull);
    });

    test('reads the tracking link on the sender receipt', () {
      final c = parseScannedCode('https://localhost:5173/track/PA-DEMO-00000000000#t=abc_DEF-123');
      expect(c.trackingId, 'PA-DEMO-00000000000');
      expect(c.token, 'abc_DEF-123');
    });
  });
}
